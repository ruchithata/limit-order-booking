"""Deterministic price-time-priority matching engine."""

from engine.order import Order, OrderId, Trade
from engine.order_book import LevelSnapshot, OrderBook, OrderBookSnapshot
from engine.types import OrderType, Side


class MatchingEngine:
    """Match incoming orders against resting liquidity in an OrderBook."""

    def __init__(self, order_book: OrderBook | None = None) -> None:
        self.order_book = order_book if order_book is not None else OrderBook()
        self._next_trade_id = 1

    def __len__(self) -> int:
        """Return the number of active orders in the underlying book."""
        return len(self.order_book)

    def submit_order(self, order: Order) -> list[Trade]:
        """Submit an order and return the trades generated by the submission."""
        if not isinstance(order, Order):
            raise TypeError("order must be an Order")
        if order.is_cancelled:
            raise ValueError("cancelled orders cannot be submitted")
        if order.is_filled:
            raise ValueError("filled orders cannot be submitted")
        if self.order_book.get_order(order.order_id) is not None:
            raise ValueError(f"duplicate active order ID: {order.order_id!r}")

        trades: list[Trade] = []
        resting_side = Side.SELL if order.side is Side.BUY else Side.BUY

        while order.remaining_quantity > 0:
            resting_order = self.order_book.peek_best_order(resting_side)
            if resting_order is None:
                break
            if not self._prices_cross(order, resting_order):
                break

            fill_quantity = min(
                order.remaining_quantity, resting_order.remaining_quantity
            )
            execution_price = resting_order.price
            if execution_price is None:
                raise RuntimeError("a resting limit order must have a price")

            level = (
                self.order_book.best_ask_level()
                if resting_side is Side.SELL
                else self.order_book.best_bid_level()
            )
            if level is None:
                raise RuntimeError("best order exists without a price level")
            level.apply_fill_to_front(fill_quantity)

            if resting_order.is_filled:
                removed = self.order_book.pop_best_order(resting_side)
                if removed is not resting_order:
                    raise RuntimeError("order-book best order changed unexpectedly")

            order.apply_fill(fill_quantity)
            buy_order_id = (
                order.order_id if order.side is Side.BUY else resting_order.order_id
            )
            sell_order_id = (
                order.order_id if order.side is Side.SELL else resting_order.order_id
            )
            trades.append(
                Trade(
                    trade_id=self._next_trade_id,
                    buy_order_id=buy_order_id,
                    sell_order_id=sell_order_id,
                    price=execution_price,
                    quantity=fill_quantity,
                    maker_order_id=resting_order.order_id,
                    taker_order_id=order.order_id,
                )
            )
            self._next_trade_id += 1

        if order.remaining_quantity > 0:
            if order.order_type is OrderType.LIMIT:
                self.order_book.add_order(order)
            else:
                order.cancel()
        return trades

    def cancel_order(self, order_id: OrderId) -> bool:
        """Cancel an active resting order; return False for unknown IDs."""
        return self.order_book.cancel_order(order_id)

    def get_order(self, order_id: OrderId) -> Order | None:
        """Look up an active order by ID; return None if not found."""
        return self.order_book.get_order(order_id)

    def best_bid_price(self) -> int | None:
        """Return the highest active buy price, or None if no bids exist."""
        return self.order_book.best_bid_price()

    def best_ask_price(self) -> int | None:
        """Return the lowest active sell price, or None if no asks exist."""
        return self.order_book.best_ask_price()

    def get_snapshot(self, depth: int | None = None) -> OrderBookSnapshot:
        """Return an immutable snapshot of the order book's bids and asks."""
        return self.order_book.get_snapshot(depth=depth)

    def snapshot(self, depth: int | None = None) -> OrderBookSnapshot:
        """Alias for get_snapshot."""
        return self.order_book.snapshot(depth=depth)

    def bids(self, depth: int | None = None) -> tuple[LevelSnapshot, ...]:
        """Return an immutable snapshot of active bid levels."""
        return self.order_book.bids(depth=depth)

    def asks(self, depth: int | None = None) -> tuple[LevelSnapshot, ...]:
        """Return an immutable snapshot of active ask levels."""
        return self.order_book.asks(depth=depth)

    get_bids = bids
    get_asks = asks

    @staticmethod
    def _prices_cross(incoming: Order, resting: Order) -> bool:
        """Return whether the incoming order can trade at the resting price."""
        if incoming.order_type is OrderType.MARKET:
            return True
        if incoming.price is None or resting.price is None:
            return False
        if incoming.side is Side.BUY:
            return resting.price <= incoming.price
        return resting.price >= incoming.price
